import { useMemo, useState } from 'react';
import { useLiveQuery } from 'dexie-react-hooks';
import { db, getSettings } from '../db';
import type { VaultItem, ContractItem, SubscriptionItem, PurchaseItem } from '../types';
import { cancellationDeadline, currentTermEnd, claimStatus, returnWindowEnd, legalGuaranteeEnd, warrantyEnd } from '../lib/calc';
import { todayISO, formatDate } from '../lib/dates';
import { formatMoney } from '../lib/money';
import { Field } from '../components/ui';
import { copyText } from '../lib/compat';
import { t } from '../lib/i18n';

const NOT_LEGAL_ADVICE = 'Note: this letter was generated by the app for your convenience. It is not legal advice.';

function buildCancellationLetter(item: ContractItem | SubscriptionItem, method: { name: string; last4: string; type: string } | undefined, today: string): { subject: string; body: string } {
  const isContract = item.kind === 'contract';
  let deadline: string, termEnd: string;
  if (isContract) {
    const d = cancellationDeadline(item as ContractItem, today);
    deadline = d.deadline; termEnd = d.termEnd;
  } else {
    const s = item as SubscriptionItem;
    if (s.minTermMonths) {
      const pseudo = { ...s, kind: 'contract', startDate: s.firstChargeDate, minTermMonths: s.minTermMonths, renewalPeriodMonths: 1, noticePeriodMonths: 1 } as ContractItem;
      const d = cancellationDeadline(pseudo, today);
      deadline = d.deadline; termEnd = d.termEnd;
    } else {
      deadline = today; termEnd = today;
    }
  }
  const acc = item.account ?? {};
  const lines = [
    'Dear Sir or Madam,',
    '',
    `I hereby cancel my ${item.kind} "${item.title}" (${formatMoney(item.price, item.currency)} every ${item.interval}).`,
    acc.customerNumber ? `Customer number: ${acc.customerNumber}` : '',
    acc.contractNumber ? `Contract number: ${acc.contractNumber}` : '',
    '',
    `Earliest possible end of contract: ${formatDate(termEnd)}. Please confirm this date in writing.`,
    `The cancellation deadline for this term is ${formatDate(deadline)}.`,
    method?.type === 'bank' ? `I pay by direct debit (account ••${method.last4}). Please revoke the direct debit authorisation with effect from the end of the contract and confirm this to me in writing.` : '',
    '',
    'Please send me a written confirmation of receipt and of the end date of the contract.',
    '',
    'Kind regards',
    '',
    NOT_LEGAL_ADVICE
  ].filter((l, i, arr) => !(l === '' && arr[i - 1] === ''));
  return { subject: `Cancellation of ${item.title}${acc.contractNumber ? ` (contract ${acc.contractNumber})` : ''}`, body: lines.join('\n') };
}

function buildClaimLetter(item: PurchaseItem, today: string): { subject: string; body: string } {
  const status = claimStatus(item, today);
  const acc = item.account ?? {};
  const sellerContact = [acc.cancelEmail, acc.cancelPhone, acc.cancelUrl].filter(Boolean).join(' · ') || 'the seller (see your order confirmation)';
  const head = [
    'Dear Sir or Madam,',
    '',
    `I am writing about my purchase "${item.title}"` + (item.orderNumber ? ` (order no. ${item.orderNumber}` : '') + (item.serialNumber ? `, serial no. ${item.serialNumber}` : '') + `), bought on ${formatDate(item.purchaseDate)} for ${formatMoney(item.price, item.currency)}.`,
    ''
  ];
  let body: string;
  if (status === 'return') {
    body = `The item does not meet my expectations. I am within the ${item.returnWindowDays}-day return window (until ${formatDate(returnWindowEnd(item))}) and hereby return it. Please refund ${formatMoney(item.price, item.currency)} to my payment method.`;
  } else if (status === 'legal-guarantee') {
    body = `The item is defective. Under the statutory legal guarantee (${item.legalGuaranteeMonths} months, valid until ${formatDate(legalGuaranteeEnd(item))}) I request repair or replacement free of charge. Please contact me within the legal deadline to arrange this.`;
  } else if (status === 'manufacturer-warranty' || status === 'extended-warranty') {
    const months = status === 'manufacturer-warranty' ? item.warrantyMonths! : item.extendedWarrantyMonths!;
    body = `The item is defective. The ${status === 'manufacturer-warranty' ? 'manufacturer warranty' : 'extended warranty'} (${months} months, valid until ${formatDate(warrantyEnd(item, months))}) still applies. Please repair or replace the item under warranty.`;
  } else {
    body = `The item is defective, but no return window, legal guarantee or warranty appears to still apply (legal guarantee ended ${formatDate(legalGuaranteeEnd(item))}). I still request a goodwill solution. Contact: ${sellerContact}.`;
  }
  const lines = [...head, body, '', 'Kind regards', '', NOT_LEGAL_ADVICE];
  return { subject: `${status === 'return' ? 'Return' : 'Warranty claim'} — ${item.title}`, body: lines.join('\n') };
}

export default function Assistants({ itemId }: { itemId?: string }) {
  const items = useLiveQuery(() => db.items.toArray());
  const methods = useLiveQuery(() => db.paymentMethods.toArray());
  const settings = useLiveQuery(() => getSettings());
  const [selectedId, setSelectedId] = useState<string | undefined>(itemId);
  const [tab, setTab] = useState<'cancel' | 'claim'>('cancel');
  const [copied, setCopied] = useState(false);

  const selected = useMemo(() => items?.find(i => i.id === selectedId), [items, selectedId]);
  const today = todayISO();

  if (!items || !methods || !settings) return <p className="muted">{t('Loading…')}</p>;

  const cancellable = items.filter(i => i.kind === 'contract' || i.kind === 'subscription');
  const purchasable = items.filter(i => i.kind === 'purchase');

  let letter: { subject: string; body: string } | null = null;
  let letterItem: VaultItem | null = null;
  if (selected) {
    const method = methods.find(m => m.id === selected.paymentMethodId);
    if (tab === 'cancel' && (selected.kind === 'contract' || selected.kind === 'subscription')) {
      letter = buildCancellationLetter(selected as ContractItem, method, today);
      letterItem = selected;
    }
    if (tab === 'claim' && selected.kind === 'purchase') {
      letter = buildClaimLetter(selected, today);
      letterItem = selected;
    }
  }

  const copy = async () => {
    if (!letter) return;
    const ok = await copyText(`Subject: ${letter.subject}\n\n${letter.body}`);
    setCopied(ok);
    setTimeout(() => setCopied(false), 2000);
  };

  const openMail = () => {
    if (!letter) return;
    const acc = letterItem?.account;
    const to = tab === 'cancel' && acc?.cancelEmail ? acc.cancelEmail : '';
    window.location.href = `mailto:${to}?subject=${encodeURIComponent(letter.subject)}&body=${encodeURIComponent(letter.body)}`;
  };

  return (
    <div>
      <h1>🤖 {t('Assistants')}</h1>
      <p className="muted">{t('The app writes the letter for you — you copy it or open it in your own email app. Receipt Vault never sends anything itself.')}</p>

      <div className="tabs">
        <button className={`btn ${tab === 'cancel' ? 'primary' : ''}`} onClick={() => { setTab('cancel'); setSelectedId(undefined); }}>✉️ {t('Write cancellation')}</button>
        <button className={`btn ${tab === 'claim' ? 'primary' : ''}`} onClick={() => { setTab('claim'); setSelectedId(undefined); }}>🛠 {t("Something's wrong with it")}</button>
      </div>

      <Field label={t('Choose an item')}>
        <select value={selectedId ?? ''} onChange={e => setSelectedId(e.target.value || undefined)}>
          <option value="">{t('— choose —')}</option>
          {(tab === 'cancel' ? cancellable : purchasable).map(i => (
            <option key={i.id} value={i.id}>{i.title} ({i.kind})</option>
          ))}
        </select>
      </Field>

      {selected && tab === 'cancel' && selected.kind === 'contract' && (() => {
        const d = cancellationDeadline(selected as ContractItem, today);
        return <div className="banner info">ℹ {t('Earliest end date:')} <b>{formatDate(d.termEnd)}</b> · {t('cancellation deadline:')} <b>{formatDate(d.deadline)}</b></div>;
      })()}
      {selected && tab === 'claim' && selected.kind === 'purchase' && (
        <div className="banner info">ℹ {t('Protection that still applies:')} <b>{claimStatus(selected, today)}</b></div>
      )}

      {letter && (
        <div className="card">
          <h3>{letter.subject}</h3>
          <div className="letter">{letter.body}</div>
          <div className="btn-row">
            <button className="btn primary" onClick={copy}>{copied ? `✅ ${t('Copied!')}` : `📋 ${t('Copy')}`}</button>
            <button className="btn" onClick={openMail}>📧 {t('Open in my email app')}</button>
          </div>
          <p className="muted">{t('This letter was generated by the app for your convenience. It is not legal advice.')}</p>
        </div>
      )}
    </div>
  );
}
